//  데이터그램(UDP) 경로를 **언제** 뚫을 것인가. 값 하나짜리 설정이지만 그 하나가 세션의
//  유지 비용과 첫 화면까지의 시간을 맞바꾼다.
//
//  ## 왜 기본이 '나중에'인가
//
//  NAT의 UDP 매핑은 수명이 짧다(흔히 30초 안팎, 캐리어 CGNAT은 더). 붙들고 있으려면 아무도
//  안 보는 동안에도 계속 두드려야 하고, 그건 무선 라디오를 계속 깨우는 일이다. TCP 매핑은
//  분~시간 단위로 살아 있어서, 제어 채널 하나만 쥐고 있으면 세션은 값싸게 유지된다.
//  알림만 쓰는 세션이 UDP 소켓·NAT 매핑·keepalive를 갖고 있을 이유가 없다.
//
//  ## 그런데도 미리 뚫어야 할 때가 있다
//
//  **세션이 서는 그 순간 영상 앱이 곧바로 붙어야 하는 경우**다. 두 가지가 그렇다:
//
//   · 지난번에 켜 둔 앱이 UDP를 쓰는 앱이었다 — 붙자마자 `AppLaunchStore`가 그걸 되띄운다.
//   · 망이 바뀌어 채널이 통째로 다시 서고 있다 — 그 전까지 화면이 흐르고 있었으므로
//     사용자에게는 "끊겼다 돌아오는 시간"이 그대로 보인다.
//
//  그때는 앱이 뜨고 나서 ICE 한 왕복을 더 기다리는 게 눈에 띈다. 이 스위치를 켜면 접속하는
//  그 라운드에서 UDP까지 함께 뚫어 두고, 첫 세대가 그 경로를 그대로 물려받는다.
//
//  ## 켜도 수명 규칙은 그대로다
//
//  **마지막 영상 앱이 내려가면 세대는 닫힌다.** 이 스위치가 바꾸는 건 "언제 뚫는가"이지
//  "얼마나 붙들고 있는가"가 아니다 — 세션 내내 매핑을 유지하는 건 애초에 이 설계가 피하려던
//  것이고, 아무도 안 쓰는 구멍을 붙들 이유는 fast 모드에서도 생기지 않는다.
//
//  경로를 잃어도 되찾을 길이 있다는 것이 기본을 '나중에'로 둘 수 있는 근거다 — BLE가
//  대역 밖에서 재수립을 돕는다.
//

import Foundation

enum DatagramSettings {
    private static let fastKey = "PeriFastUdp"

    /// 접속 라운드에서 UDP까지 함께 뚫을 것인가. 기본 false.
    ///
    /// 값을 Mac이 쥐는 이유: 후보 교환을 개시하는 쪽이 Mac이고, 이 선택은 묶음의
    /// `f fastudp` 플래그로 상대에게 그대로 전달된다(`CandidateBundle`).
    static var fastUdp: Bool {
        get { UserDefaults.standard.bool(forKey: fastKey) }
        set { UserDefaults.standard.set(newValue, forKey: fastKey) }
    }
}
